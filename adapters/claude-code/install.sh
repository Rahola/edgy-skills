#!/bin/bash
# edgy-skills — Claude Code Adapter
# Asentaa skillit ~/.claude/skills/ ja päivittää CLAUDE.md
#
# Käyttö:
#   bash install.sh edgy-framework
#   bash install.sh edgy-framework edgy-assessment edgy-diagram
#   bash install.sh --all
#
# Lähde-prioriteetti (auto-detect):
#   1) Paikallinen repo (kun skripti suoritetaan repon sisältä) — kopioi koko skill-hakemisto
#   2) gh CLI (private/public repo, autentikoitu)
#   3) curl (vain public repo)
#
# Pakota lähde:
#   --source=local | --source=gh | --source=curl
#
# Versio (gh/curl-lähde): EDGY_SKILLS_REF=<tagi|haara|commit>, oletus main
#   EDGY_SKILLS_REF=v1.0.0 bash install.sh --all
# local-lähde asentaa repon nykyisestä checkoutista (git checkout <tagi> ensin).
# Fork: EDGY_SKILLS_REPO=<owner/repo>

set -euo pipefail

REGISTRY_REPO="${EDGY_SKILLS_REPO:-Rahola/edgy-skills}"
REGISTRY_BRANCH="${EDGY_SKILLS_REF:-main}"
REGISTRY_BASE_URL="https://raw.githubusercontent.com/${REGISTRY_REPO}/${REGISTRY_BRANCH}"
SKILLS_DIR="${HOME}/.claude/skills"
CLAUDE_MD="${HOME}/.claude/CLAUDE.md"

# Resolvoi skriptin oma hakemisto + repo-root (jos skripti repossa)
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LOCAL_REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
LOOKUP_TOOL="${SCRIPT_DIR}/../../tools/lookup-skill.py"

# Värit terminaalitulosteeseen
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

log_info()    { echo -e "${GREEN}✓${NC} $1"; }
log_warn()    { echo -e "${YELLOW}⚠${NC} $1"; }
log_error()   { echo -e "${RED}✗${NC} $1" >&2; }

# Lähde-strategia (paikallinen / gh / curl)
SOURCE_MODE=""

# Tarkista yleiset riippuvuudet
check_dependencies() {
  if ! command -v python3 &>/dev/null; then
    log_error "python3 ei löydy. Asenna python3 ja yritä uudelleen."
    exit 1
  fi
}

# Päättele lähdetila
detect_source() {
  # Jos käyttäjä pakotti, käytetään sitä
  if [[ -n "$SOURCE_MODE" ]]; then
    case "$SOURCE_MODE" in
      local|gh|curl) ;;
      *) log_error "Tuntematon --source: $SOURCE_MODE (sallitut: local, gh, curl)"; exit 1 ;;
    esac
    return
  fi

  # Auto-detect:
  # 1. Paikallinen repo (skripti repon sisällä + registry.yaml löytyy)
  if [[ -f "${LOCAL_REPO_ROOT}/registry.yaml" ]]; then
    SOURCE_MODE="local"
    log_info "Lähde: paikallinen repo (${LOCAL_REPO_ROOT})"
    return
  fi

  # 2. gh CLI autentikoitu
  if command -v gh &>/dev/null && gh auth status &>/dev/null; then
    SOURCE_MODE="gh"
    log_info "Lähde: gh CLI (private/public repo)"
    return
  fi

  # 3. Fallback curl
  if command -v curl &>/dev/null; then
    SOURCE_MODE="curl"
    log_warn "Lähde: curl (vain public repo). Jos repo on private, asenna 'gh' ja autentikoi: gh auth login"
    return
  fi

  log_error "Ei sopivaa lähdettä: paikallista repoa ei löydy, gh ei autentikoitu, curl puuttuu."
  exit 1
}

# Luo väliaikainen tiedosto ja rekisteröi siivous
_TMPFILES=()
_cleanup() {
  for f in "${_TMPFILES[@]:-}"; do
    [[ -n "$f" && -e "$f" ]] && rm -f "$f"
  done
  return 0
}
trap _cleanup EXIT

_new_tmp() {
  local f
  f="$(mktemp /tmp/edgy-skills.XXXXXX)"
  _TMPFILES+=("$f")
  echo "$f"
}

# Hae registry.yaml polku/sisältö valitulla lähdetilalla
fetch_registry() {
  case "$SOURCE_MODE" in
    local)
      echo "${LOCAL_REPO_ROOT}/registry.yaml"
      ;;
    gh)
      local tmp
      tmp="$(_new_tmp)"
      if ! gh api "repos/${REGISTRY_REPO}/contents/registry.yaml?ref=${REGISTRY_BRANCH}" \
           -H "Accept: application/vnd.github.raw" > "$tmp" 2>/dev/null; then
        log_error "registry.yaml:n haku epäonnistui (gh)."
        exit 1
      fi
      echo "$tmp"
      ;;
    curl)
      local tmp
      tmp="$(_new_tmp)"
      if ! curl -sfL "${REGISTRY_BASE_URL}/registry.yaml" -o "$tmp"; then
        log_error "registry.yaml:n haku epäonnistui (curl). Repo voi olla private — käytä --source=gh."
        exit 1
      fi
      echo "$tmp"
      ;;
  esac
}

# Etsi skillin polku registry.yaml:sta
get_skill_path() {
  local skill_id="$1"
  local registry_file="$2"
  python3 "$LOOKUP_TOOL" path "$skill_id" "$registry_file"
}

# Listaa kaikki saatavilla olevat skill-id:t
list_all_skills() {
  local registry_file="$1"
  python3 "$LOOKUP_TOOL" list "$registry_file"
}

# Päivitä CLAUDE.md lisäämällä skill-viittaus
update_claude_md() {
  local skill_id="$1"

  # Luo CLAUDE.md jos se ei ole olemassa
  if [[ ! -f "$CLAUDE_MD" ]]; then
    cat > "$CLAUDE_MD" <<EOF
# CLAUDE.md

## Available Skills
<!-- auto-generated by edgy-skills install.sh -->
EOF
  fi

  # Lisää Skills-osio jos se puuttuu
  if ! grep -q "## Available Skills" "$CLAUDE_MD" 2>/dev/null; then
    cat >> "$CLAUDE_MD" <<EOF

## Available Skills
<!-- auto-generated by edgy-skills install.sh -->
EOF
  fi

  # Lisää skill-viittaus jos se ei ole jo siellä
  if ! grep -q "@skills/${skill_id}" "$CLAUDE_MD" 2>/dev/null; then
    if [[ "$(uname)" == "Darwin" ]]; then
      sed -i '' "/## Available Skills/a\\
@skills/${skill_id}" "$CLAUDE_MD"
    else
      sed -i "/## Available Skills/a @skills\/${skill_id}" "$CLAUDE_MD"
    fi
    log_info "Lisätty @skills/${skill_id} → ${CLAUDE_MD}"
  else
    log_warn "Skill '${skill_id}' on jo CLAUDE.md:ssä"
  fi
}

# Kopioi skillin sisältö paikallisesta reposta
copy_local() {
  local skill_path="$1"
  local target_dir="$2"
  local src="${LOCAL_REPO_ROOT}/${skill_path}"

  if [[ ! -d "$src" ]]; then
    log_error "Paikallista skill-hakemistoa ei löydy: ${src}"
    return 1
  fi

  rm -rf "$target_dir"
  mkdir -p "$(dirname "$target_dir")"
  cp -r "$src" "$target_dir"
}

# Lataa skillin sisältö gh:lla (rekursiivisesti — tar via gh api)
fetch_gh() {
  local skill_path="$1"
  local target_dir="$2"

  local tarball
  tarball="$(_new_tmp)"

  # Lataa koko repo tarballina ja pura vain haluttu polku
  if ! gh api "repos/${REGISTRY_REPO}/tarball/${REGISTRY_BRANCH}" > "$tarball" 2>/dev/null; then
    log_error "Tarball-lataus epäonnistui (gh)."
    return 1
  fi

  rm -rf "$target_dir"
  mkdir -p "$target_dir"

  # Tarball: <prefix>/<skill_path>/... → strip = 1 (prefix) + slashes_in_skill_path + 1 (skill_path:n viimeinen segmentti)
  local slashes="${skill_path//[^\/]/}"
  local strip=$(( ${#slashes} + 2 ))

  if ! tar -xzf "$tarball" -C "$target_dir" --strip-components="$strip" --wildcards "*/${skill_path}/*" 2>/dev/null; then
    log_error "Tarballin purku epäonnistui (path: ${skill_path}, strip=${strip})."
    return 1
  fi
}

# Lataa skillin SKILL.md curl:lla (vain public repot)
fetch_curl() {
  local skill_path="$1"
  local target_dir="$2"

  mkdir -p "$target_dir"
  local url="${REGISTRY_BASE_URL}/${skill_path}/SKILL.md"
  if ! curl -sfL "$url" -o "${target_dir}/SKILL.md"; then
    log_error "SKILL.md:n lataus epäonnistui (curl): ${url}"
    return 1
  fi
  log_warn "curl-tila lataa vain SKILL.md (ei examples/scripts/-alikansioita). Käytä --source=gh tai paikallista repoa täydelle asennukselle."
}

# Asenna yksittäinen skill
install_skill() {
  local skill_id="$1"
  local registry_file="$2"

  # Validoi skill_id – salli vain kirjaimet, numerot, viiva ja alaviiva
  if [[ ! "$skill_id" =~ ^[a-zA-Z0-9_-]+$ ]]; then
    log_error "Virheellinen skill-id: '${skill_id}'. Sallittu: a-z, A-Z, 0-9, - ja _"
    return 1
  fi

  echo "Asennetaan skill: ${skill_id}..."

  local skill_path
  if ! skill_path=$(get_skill_path "$skill_id" "$registry_file"); then
    log_error "Skilliä '${skill_id}' ei löydy registry.yaml:sta."
    log_warn "Saatavilla olevat skillit:"
    list_all_skills "$registry_file" | sed 's/^/  - /'
    return 1
  fi

  local target_dir="${SKILLS_DIR}/${skill_id}"

  case "$SOURCE_MODE" in
    local) copy_local "$skill_path" "$target_dir" || return 1 ;;
    gh)    fetch_gh    "$skill_path" "$target_dir" || return 1 ;;
    curl)  fetch_curl  "$skill_path" "$target_dir" || return 1 ;;
  esac

  log_info "Skill '${skill_id}' ladattu → ${target_dir}"

  update_claude_md "$skill_id"

  log_info "Skill '${skill_id}' asennettu onnistuneesti!"
}

# --- Pääohjelma ---

# Parsi flagit (--source=...) ja erottele skill-id:t
ARGS=()
for arg in "$@"; do
  case "$arg" in
    --source=*) SOURCE_MODE="${arg#--source=}" ;;
    --help|-h)
      echo "Käyttö: $0 [--source=local|gh|curl] <skill-id> [skill-id2 ...]"
      echo "        $0 [--source=local|gh|curl] --all"
      echo ""
      echo "Esimerkit:"
      echo "  $0 edgy-framework"
      echo "  $0 edgy-framework edgy-assessment"
      echo "  $0 --all"
      echo "  $0 --source=gh confluence-to-obsidian"
      exit 0
      ;;
    *) ARGS+=("$arg") ;;
  esac
done

if [[ ${#ARGS[@]} -eq 0 ]]; then
  echo "Käyttö: $0 [--source=local|gh|curl] <skill-id> [skill-id2 ...]"
  echo "        $0 [--source=local|gh|curl] --all"
  echo ""
  echo "Esimerkit:"
  echo "  $0 edgy-framework"
  echo "  $0 --all"
  echo "  $0 --source=gh confluence-to-obsidian"
  exit 1
fi

check_dependencies
detect_source

# Varmista skills-hakemisto
mkdir -p "$SKILLS_DIR"

# Hae registry
registry_file=$(fetch_registry)

if [[ "${ARGS[0]}" == "--all" ]]; then
  echo "Asennetaan kaikki skillit..."
  while IFS= read -r skill_id; do
    skill_id="${skill_id%$'\r'}"
    [[ -z "$skill_id" ]] && continue
    install_skill "$skill_id" "$registry_file" || true
  done < <(list_all_skills "$registry_file")
else
  for skill_id in "${ARGS[@]}"; do
    skill_id="${skill_id%$'\r'}"
    install_skill "$skill_id" "$registry_file"
  done
fi

echo ""
log_info "Asennus valmis! Käynnistä Claude Code uudelleen nähdäksesi skillit."
