#!/bin/bash
# edgy-skills — Cursor Adapter
# Generoi .cursorrules tiedoston valituista skillseistä (vain SKILL.md-sisältö)
#
# Käyttö:
#   bash install.sh edgy-framework
#   bash install.sh edgy-framework edgy-assessment
#   bash install.sh --all
#   bash install.sh --source=gh edgy-framework      # pakota gh-lähde (private repo)
#   bash install.sh --source=local edgy-framework   # tästä checkoutista, ei verkkoa
#
# Cursor saa vain SKILL.md:n. Skill, joka tarvitsee skriptinsä (registryssä
# install: directory, esim. edgy-c4), torjutaan viestillä; --all ohittaa sen ja
# nimeää sen. Mikä tahansa virhe → exit 1, eikä valmis-riviä tulosteta.

set -euo pipefail

# Lataa jaettu lähdestrategia
ADAPTER_SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "${ADAPTER_SCRIPT_DIR}/../_shared/source.sh"
source "${ADAPTER_SCRIPT_DIR}/../_shared/deps.sh"

CURSORRULES_FILE="${PWD}/.cursorrules"

log_info()  { echo -e "${GREEN}✓${NC} $1"; }
log_warn()  { echo -e "${YELLOW}⚠${NC} $1"; }
log_error() { echo -e "${RED}✗${NC} $1" >&2; }

# Parsi --source=... ja skill-id:t
ARGS=()
for arg in "$@"; do
  case "$arg" in
    --source=*) SOURCE_MODE="${arg#--source=}" ;;
    --help|-h)
      echo "Käyttö: $0 [--source=local|gh|curl] <skill-id> [skill-id2 ...] | --all"
      exit 0
      ;;
    *) ARGS+=("$arg") ;;
  esac
done

if [[ ${#ARGS[@]} -eq 0 ]]; then
  echo "Käyttö: $0 [--source=local|gh|curl] <skill-id> [skill-id2 ...] | --all"
  exit 1
fi

if ! command -v python3 &>/dev/null; then
  log_error "python3 ei löydy."
  exit 1
fi

source_detect
log_info "Lähde: ${SOURCE_MODE}"

registry_file=$(deps_registry_override) || registry_file=$(source_fetch_registry) || exit 1

FAILED=()
REQUESTED=()
if [[ "${ARGS[0]}" == "--all" ]]; then
  if ! all_ids=$(deps_list_or_fail "$registry_file"); then
    log_error "Rekisteristä ei saatu skillilistaa — .cursorrules jätettiin ennalleen."
    exit 1
  fi
  while IFS= read -r skill_id; do
    skill_id="${skill_id%$'\r'}"
    [[ -z "$skill_id" ]] && continue
    if ! reason=$(deps_supports "$skill_id" "$registry_file" "cursor" "skillmd" 2>&1); then
      log_warn "Ohitetaan ${skill_id}: ${reason}"
      continue
    fi
    REQUESTED+=("$skill_id")
  done <<< "$all_ids"
else
  REQUESTED=("${ARGS[@]}")
fi

# Ratkaise asennusjärjestys (riippuvuudet ensin) ja tarkista tuki ennen kirjoittamista
ORDER=()
for skill_id in "${REQUESTED[@]}"; do
  if ! order=$(deps_install_order "$skill_id" "$registry_file"); then
    FAILED+=("$skill_id")
    continue
  fi
  ok=true
  while IFS= read -r sid; do
    [[ -z "$sid" ]] && continue
    deps_supports "$sid" "$registry_file" "cursor" "skillmd" || ok=false
  done <<< "$order"
  if [[ "$ok" != true ]]; then
    FAILED+=("$skill_id")
    continue
  fi
  while IFS= read -r sid; do
    [[ -z "$sid" ]] && continue
    [[ " ${ORDER[*]:-} " == *" ${sid} "* ]] || ORDER+=("$sid")
  done <<< "$order"
done

if [[ ${#ORDER[@]} -gt 0 ]]; then
  # Aloita .cursorrules
  {
    echo "# .cursorrules — Generated by edgy-skills"
    echo "# Source: ${SOURCE_MODE} (${REGISTRY_REPO}@${REGISTRY_BRANCH})"
    echo "# Generated: $(date -u +"%Y-%m-%dT%H:%M:%SZ")"
    echo "#"
    echo "# Skills included:"
    for skill in "${ORDER[@]}"; do echo "#   - $skill"; done
    echo ""
  } > "$CURSORRULES_FILE"

  for skill_id in "${ORDER[@]}"; do
    if ! skill_path=$(python3 "$LOOKUP_TOOL" path "$skill_id" "$registry_file"); then
      FAILED+=("$skill_id")
      continue
    fi
    body=""
    if ! body=$(source_fetch_file "${skill_path}/SKILL.md") || [[ -z "$body" ]]; then
      log_error "SKILL.md:n haku epäonnistui: ${skill_path}/SKILL.md"
      FAILED+=("$skill_id")
      continue
    fi
    {
      echo "---"
      echo "# SKILL: ${skill_id}"
      echo ""
      printf '%s\n' "$body"
      echo ""
    } >> "$CURSORRULES_FILE"
    log_info "Skill '${skill_id}' lisätty .cursorrules:iin"
  done
fi

if [[ ${#FAILED[@]} -gt 0 ]]; then
  log_error "Epäonnistui: ${FAILED[*]} (${#FAILED[@]} skilliä)."
  exit 1
fi
log_info "Valmis! ${CURSORRULES_FILE} on päivitetty."
