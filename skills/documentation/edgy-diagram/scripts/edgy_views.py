#!/usr/bin/env python3
"""
edgy_views.py — derived architecture views (edgy-diagram 2.8.0).

A derived view is a page whose content comes from the document graph
(edgy_graph) instead of being typed again: the capability view of one
capability, the capability × application and CRUD matrices, and the views
generated by `expand:`. `materialize(parser, graph)` writes the view's
elements and relationships into the page's parser as ordinary TXT lines, so
every existing parser rule (vocabulary, pair validation, sizes, legend)
applies unchanged.

Standard library only.
"""

from typing import List

DERIVED_MAP_TYPES = set()   # filled by the view sprints (capability-view, capability-matrix, …)


def is_derived(parser) -> bool:
    return (parser.map_type or '') in DERIVED_MAP_TYPES


def materialize(parser, graph) -> None:
    """Fill a derived view page from the graph (no-op for ordinary pages)."""
    return None


def quote(text: str) -> str:
    return '"' + (text or '').replace('"', "'") + '"'


def element_line(node: dict, extra: dict = None, indent: str = '  ') -> str:
    """One `- type: "name - description" [tags] {id: …, …}` line for a graph node."""
    value = node['name'] + (f" - {node['subtext']}" if node.get('subtext') else '')
    opts = {'id': node['id']}
    if node.get('kind'):
        opts['kind'] = node['kind']
    for k, v in (node.get('attrs') or {}).items():
        if k != 'kind':
            opts[k] = v
    if node.get('change'):
        opts['change'] = node['change']
    if node.get('maturity'):
        opts['maturity'] = node['maturity']
    if node.get('rating'):
        opts['rating'] = node['rating']
    opts.update(extra or {})
    body = ', '.join(f"{k}: {_val(v)}" for k, v in opts.items() if v not in (None, ''))
    tags = [t for t in node.get('tags') or [] if t]
    tag_s = f" [{', '.join(tags)}]" if tags else ''
    return f"{indent}- {node['type']}: {quote(value)}{tag_s} {{{body}}}"


def _val(v) -> str:
    s = str(v)
    return f'"{s}"' if (',' in s or ':' in s) else s


def relationship_line(source: str, target: str, verb: str, options: dict = None, indent: str = '  ') -> str:
    opts = options or {}
    parts = []
    for k in ('crud', 'technology', 'container', 'change', 'from', 'to'):
        if opts.get(k):
            parts.append(f"{k}: {_val(opts[k])}")
    if opts.get('data'):
        parts.append("data: " + _val('; '.join(opts['data'])))
    tail = f" {{{', '.join(parts)}}}" if parts else ''
    return f"{indent}- {quote(source)} -> {quote(target)}: {quote(verb)}{tail}"
